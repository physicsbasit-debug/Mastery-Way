export const ACADEMIC_YEAR_START_MONTH = 9;

export function getQuestionTypeOptionsForCategory(category: string): readonly string[] {
  return QUESTION_TYPE_OPTIONS_BY_CATEGORY[category as QuestionCategory] || QUESTION_TYPE_OPTIONS;
}

export function getDefaultQuestionTypeForCategory(category: string): string {
  return getQuestionTypeOptionsForCategory(category)[0] || 'أخرى';
}

function normalizeArabicKey(value: string): string {
  return value.replace(/[\sـ]/g, '').trim();
}

export function getErrorTypeOptionsForSkill(skill: string): readonly string[] {
  const normalized = normalizeArabicKey(skill || '');
  const skillKey = (Object.keys(ERROR_TYPE_OPTIONS_BY_SKILL) as Array<keyof typeof ERROR_TYPE_OPTIONS_BY_SKILL>)
    .find((key) => normalized.includes(normalizeArabicKey(key)) || normalizeArabicKey(key).includes(normalized));
  const skillSpecific = skillKey ? ERROR_TYPE_OPTIONS_BY_SKILL[skillKey] : [];
  return Array.from(new Set([...COMMON_ERROR_TYPE_OPTIONS, ...skillSpecific, 'أخرى']));
}

export function getLocalDateString(date = new Date()): string {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

export function getAcademicYearFromDate(date = new Date(), startMonth = ACADEMIC_YEAR_START_MONTH): string {
  const currentYear = date.getFullYear();
  const currentMonth = date.getMonth() + 1;
  const startYear = currentMonth >= startMonth ? currentYear : currentYear - 1;
  return `${startYear}/${startYear + 1} م`;
}
